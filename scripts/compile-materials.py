"""Pack only used LPC crops; retain original sources and mandatory credits."""
from pathlib import Path
import re,json
from PIL import Image
root=Path(__file__).resolve().parents[1]
code=(root/'src/lpc-surfaces.js').read_text()
floor_section=code.split('const tiles = {',1)[1].split('};',1)[0]
wall_section=code.split('const crop={',1)[1].split('}[kind]',1)[0]
floors=sorted(set(tuple(map(int,p))for p in re.findall(r'\[(\d+),(\d+)\]',floor_section)))
walls=sorted(set(tuple(map(int,p))for p in re.findall(r'\[(\d+),(\d+)\]',wall_section)))
walls.append((0,2656));walls=sorted(set(walls))
images={k:Image.open(root/f'public/assets/lpc/{k}.png').convert('RGBA')for k in ['floors','walls']}
out=Image.new('RGBA',(256,384));layout={'floors':{},'rugs':{},'walls':{}}
for i,(x,y)in enumerate(floors):
 dst=(i%8*32,i//8*32);out.paste(images['floors'].crop((x,y,x+32,y+32)),dst);layout['floors'][f'{x},{y}']=dst
for i,y in enumerate([64,224,384,544]):
 dst=(i%2*96,64+i//2*96);out.paste(images['floors'].crop((96,y,192,y+96)),dst);layout['rugs'][str(y)]=dst
for i,(x,y)in enumerate(walls):
 dst=(i%8*32,256+i//8*64);out.paste(images['walls'].crop((x,y,x+32,y+64)),dst);layout['walls'][f'{x},{y}']=dst
out.save(root/'public/assets/lpc/haveli-materials.png',optimize=True)
(root/'src/lpc-material-layout.js').write_text('// Generated by scripts/compile-materials.py from credited LPC atlases.\nexport const materialLayout = '+json.dumps(layout,separators=(',',':'))+';\n')
print('Compiled materials:',out.size,(root/'public/assets/lpc/haveli-materials.png').stat().st_size,'bytes')
